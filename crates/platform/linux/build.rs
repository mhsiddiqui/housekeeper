//! Registers every source in `src/sources/`, every package tool in `src/tools/` and every recipe in `recipes/`
//! automatically.
//!
//! Each `*.rs` file in the code folders (except `mod.rs`) becomes a module, and its registration constant goes into the
//! folder's list: `PROVIDER` into `PROVIDERS`, `TOOL` into `TOOLS`. The file defines the constant with
//! `register!(<Type>);` or `register_package_tool!(<Type>);`, so the compiler reports a file that forgets it. Each
//! `*.toml` file in `recipes/` is compiled in as text and listed in `RECIPE_FILES` with its name; `recipe.rs` parses
//! it. The script never reads the files' contents, so adding a provider, a tool or a recipe never requires editing a
//! list.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// One folder of self-registering files.
struct Folder {
    dir: &'static str,
    /// The constant each file defines, and the macro that defines it.
    constant: &'static str,
    macro_call: &'static str,
    /// The generated list and its type.
    list: &'static str,
    item_type: &'static str,
    what: &'static str,
}

const FOLDERS: [Folder; 2] = [
    Folder {
        dir: "sources",
        constant: "PROVIDER",
        macro_call: "register!(<Type>);` for its `impl LinuxSource for <Type>`",
        list: "PROVIDERS",
        item_type: "crate::provider::Provider",
        what: "source",
    },
    Folder {
        dir: "tools",
        constant: "TOOL",
        macro_call: "register_package_tool!(<Type>);` for its `impl LinuxTool for <Type>`",
        list: "TOOLS",
        item_type: "crate::provider::ToolProvider",
        what: "package tool",
    },
];

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    for folder in &FOLDERS {
        generate(folder, &manifest_dir.join("src").join(folder.dir), &out_dir);
    }
    generate_recipes(&manifest_dir.join("recipes"), &out_dir);
}

/// The files in `dir` with extension `ext`, sorted. Cargo reruns this script when any file in `dir` changes.
fn files(dir: &Path, ext: &str) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("readable directory entry").path())
        .filter(|path| path.extension().is_some_and(|found| found == ext))
        .collect();
    files.sort();
    files
}

fn generate_recipes(dir: &Path, out_dir: &Path) {
    let mut items = String::new();
    for file in files(dir, "toml") {
        let key = file.file_stem().and_then(|s| s.to_str()).expect("UTF-8 file name");
        assert!(
            !key.is_empty()
                && key
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
            "{}: recipe file names are lowercase letters, digits and `-`",
            file.display()
        );
        writeln!(items, "    ({key:?}, include_str!({:?})),", file.display().to_string()).expect("write to String");
    }
    let generated = format!(
        "// Generated by build.rs from the files in recipes/. Do not edit.\n\n\
         /// Every recipe in `recipes/`, in file-name order: its key (the file name) and its text.\n\
         static RECIPE_FILES: &[(&str, &str)] = &[\n{items}];\n"
    );
    let out = out_dir.join("recipes.rs");
    fs::write(&out, generated).unwrap_or_else(|e| panic!("cannot write {}: {e}", out.display()));
}

fn generate(folder: &Folder, dir: &Path, out_dir: &Path) {
    let files: Vec<PathBuf> = files(dir, "rs")
        .into_iter()
        .filter(|path| !path.ends_with("mod.rs"))
        .collect();

    let mut modules = String::new();
    let mut items = String::new();
    for file in &files {
        let module = file.file_stem().and_then(|s| s.to_str()).expect("UTF-8 file name");
        assert!(
            is_identifier(module),
            "{}: file names in src/{}/ must be valid Rust identifiers (lowercase letters, digits, `_`)",
            file.display(),
            folder.dir
        );
        writeln!(modules, "#[path = {:?}]\npub mod {module};", file.display().to_string()).expect("write to String");
        writeln!(
            items,
            "    // src/{}/{module}.rs must contain `{}.\n    {module}::{},",
            folder.dir, folder.macro_call, folder.constant
        )
        .expect("write to String");
    }

    let generated = format!(
        "// Generated by build.rs from the files in src/{dir}/. Do not edit.\n\n{modules}\n\
         /// Every {what} in `src/{dir}/`, in file-name order.\n\
         pub(crate) static {list}: &[{item_type}] = &[\n{items}];\n",
        dir = folder.dir,
        what = folder.what,
        list = folder.list,
        item_type = folder.item_type,
    );
    let out = out_dir.join(format!("{}.rs", folder.dir));
    fs::write(&out, generated).unwrap_or_else(|e| panic!("cannot write {}: {e}", out.display()));
}

/// A lowercase Rust identifier, so it can name a module. (A keyword such as `type` is rejected by the compiler.)
fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}
