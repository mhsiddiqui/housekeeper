//! Registers every source in `src/sources/` automatically.
//!
//! Each `*.rs` file there (except `mod.rs`) must contain exactly one `impl LinuxSource for <Type>`. The generated
//! `$OUT_DIR/sources.rs` declares the file as a module and adds `<Type>` to `PROVIDERS`, so adding a provider never
//! requires editing a list.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MARKER: &str = "impl LinuxSource for ";

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let dir = manifest_dir.join("src").join("sources");
    // A directory makes cargo rerun this script when any file in it is added, removed or changed.
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("readable directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs") && !path.ends_with("mod.rs"))
        .collect();
    files.sort();

    let mut modules = String::new();
    let mut providers = String::new();
    for file in &files {
        let module = file.file_stem().and_then(|s| s.to_str()).expect("UTF-8 file name");
        let ty = source_type(file);
        writeln!(modules, "#[path = {:?}]\npub mod {module};", file.display().to_string()).expect("write to String");
        writeln!(providers, "    crate::provider::Provider::of::<{module}::{ty}>(),").expect("write to String");
    }

    let generated = format!(
        "// Generated by build.rs from the files in src/sources/. Do not edit.\n\n{modules}\n\
         /// Every source type in `src/sources/`, in file-name order.\n\
         pub(crate) static PROVIDERS: &[crate::provider::Provider] = &[\n{providers}];\n"
    );
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo")).join("sources.rs");
    fs::write(&out, generated).unwrap_or_else(|e| panic!("cannot write {}: {e}", out.display()));
}

/// The `<Type>` in the file's single `impl LinuxSource for <Type>`.
fn source_type(file: &Path) -> String {
    let text = fs::read_to_string(file).unwrap_or_else(|e| panic!("cannot read {}: {e}", file.display()));
    let types: Vec<&str> = text
        .match_indices(MARKER)
        .map(|(at, _)| {
            let rest = &text[at + MARKER.len()..];
            let end = rest
                .find(|c: char| !(c.is_alphanumeric() || c == '_'))
                .unwrap_or(rest.len());
            &rest[..end]
        })
        .collect();
    match types.as_slice() {
        [ty] if !ty.is_empty() => (*ty).to_string(),
        _ => panic!(
            "{}: a file in src/sources/ must contain exactly one `impl LinuxSource for <Type>` (found {})",
            file.display(),
            types.len()
        ),
    }
}
